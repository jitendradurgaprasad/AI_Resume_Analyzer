import jsPDF from "jspdf";
import { ATSAuditReport } from "../analyzer/scoringEngine";
import { ParsedResume } from "../analyzer/sectionParser";
import { RoleMatchResult } from "../analyzer/rolePredictor";

export function exportAuditPdf(
  parsed: ParsedResume,
  audit: ATSAuditReport,
  primaryRole: RoleMatchResult
) {
  const doc = new jsPDF({
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 18;

  // Header banner
  doc.setFillColor(15, 23, 42); // Navy 900
  doc.rect(0, 0, pageWidth, 28, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text("AI RESUME ANALYZER & ATS AUDIT REPORT", 14, 12);

  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(148, 163, 184);
  const candidateName = parsed.contact.name || "Candidate Evaluation";
  doc.text(`Candidate: ${candidateName} | Evaluated on: ${new Date().toLocaleDateString()}`, 14, 20);

  y = 38;

  // Executive Score Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, y, pageWidth - 28, 32, 3, 3, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(26);
  doc.setTextColor(audit.overallScore >= 80 ? 16 : 220, audit.overallScore >= 80 ? 185 : 38, audit.overallScore >= 80 ? 129 : 38);
  doc.text(`${audit.overallScore}/100`, 22, y + 18);

  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(15, 23, 42);
  doc.text(`Grade: ${audit.grade} (${audit.tier} Tier)`, 70, y + 12);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`Best Fit Role: ${primaryRole.role.title} (${primaryRole.matchScore}% Match)`, 70, y + 20);
  doc.text(`Extracted Skills: ${parsed.extractedSkills.length} | Action Verbs: ${parsed.strongVerbsUsed.length} | Metrics: ${parsed.quantifiableMetricsCount}`, 70, y + 26);

  y += 40;

  // Category Breakdown
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text("ATS Scoring Breakdown", 14, y);
  y += 6;

  const categories = [
    audit.breakdown.contact,
    audit.breakdown.structure,
    audit.breakdown.actionVerbs,
    audit.breakdown.quantifiableImpact,
    audit.breakdown.skillsDensity,
  ];

  for (const cat of categories) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(51, 65, 85);
    doc.text(`${cat.title}: ${cat.score}/${cat.maxScore} (${cat.percentage}%)`, 14, y);

    // Progress bar
    doc.setFillColor(226, 232, 240);
    doc.rect(90, y - 3, 100, 3, "F");
    doc.setFillColor(16, 185, 129);
    doc.rect(90, y - 3, Math.max(2, cat.percentage), 3, "F");
    y += 6;
  }

  y += 4;

  // Recruiter Takeaway
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(14, y, pageWidth - 28, 18, 2, 2, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(15, 23, 42);
  doc.text("Executive Recruiter Takeaway:", 18, y + 6);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  const takeawayLines = doc.splitTextToSize(audit.recruiterTakeaway, pageWidth - 36);
  doc.text(takeawayLines, 18, y + 11);

  y += 26;

  // Critical Strengths & Red Flags Side-by-Side
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(16, 185, 129);
  doc.text("Key Strengths", 14, y);

  doc.setTextColor(220, 38, 38);
  doc.text("Red Flags & Attention Items", 110, y);
  y += 6;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(51, 65, 85);

  const maxItems = Math.max(audit.strengths.length, audit.redFlags.length, 1);
  for (let i = 0; i < Math.min(4, maxItems); i++) {
    if (audit.strengths[i]) {
      const s = doc.splitTextToSize(`+ ${audit.strengths[i]}`, 85);
      doc.text(s, 14, y);
    }
    if (audit.redFlags[i]) {
      const r = doc.splitTextToSize(`! ${audit.redFlags[i]}`, 85);
      doc.text(r, 110, y);
    }
    y += 8;
  }

  y += 4;

  // High Priority Action Plan
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text("Recommended Action Plan For Applicant", 14, y);
  y += 6;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  for (let i = 0; i < Math.min(3, audit.criticalFixes.length); i++) {
    const fix = doc.splitTextToSize(`${i + 1}. ${audit.criticalFixes[i]}`, pageWidth - 28);
    doc.text(fix, 14, y);
    y += 7;
  }

  // Footer
  doc.setFont("helvetica", "italic");
  doc.setFontSize(7);
  doc.setTextColor(148, 163, 184);
  doc.text("Generated by AI Resume Analyzer Enterprise Intelligence Suite", 14, 285);

  doc.save(`Resume_ATS_Audit_${candidateName.replace(/\s+/g, "_")}.pdf`);
}
